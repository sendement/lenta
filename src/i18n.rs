/// "12 ч 30 мин" / "45 min".
pub fn duration(min: u64) -> String {
    let (h, m) = (min / 60, min % 60);
    if h == 0 {
        format!("{m} {}", tr("minutes"))
    } else if h >= 10 || m == 0 {
        format!("{h} {}", tr("hours"))
    } else {
        format!("{h} {} {m} {}", tr("hours"), tr("minutes"))
    }
}
